import { executeMcpTool, type ToolTraceEntry } from "../mcp-client";
import { TUTOR_LLM_TOOLS } from "./tools";
import type {
  AgentTurnResult,
  ChatMessage,
  LlmProvider,
  ToolCall,
} from "./types";
import {
  isDontKnow,
  type EvaluateAnswerOutput,
  type GenerateQuizOutput,
  type GetMasteryOutput,
  type RecordProgressOutput,
  type SearchStudyNotesOutput,
} from "@exam-sprint/core";

const DEFAULT_MAX_ITERATIONS = 5;

const SYSTEM_PROMPT = `You are Exam Sprint, a voice-first adaptive DBMS exam tutor.
You help university students revise Database Management Systems topics based strictly on verified evidence from their own personal study notes.

Your capabilities and strict constraints:
1. Always ground your tutoring in the student's study notes. Call 'search_study_notes' to find relevant passages.
2. Call 'get_mastery' to check the student's mastery history and open misconceptions before generating questions.
3. Call 'generate_quiz' to provide a question. Never invent questions or citations; only serve questions returned by 'generate_quiz'.
4. When a student submits an answer, call 'evaluate_answer' to grade against deterministic rubrics, then call 'record_progress' to persist progress in SQLite.
5. If the student asks for an unsupported topic outside our DBMS notes, politely inform them and suggest covered topics (1NF, 2NF, 3NF, BCNF, Functional Dependencies, Normalization, ACID, Isolation Levels).
6. Provide concise, friendly explanations that explain why an answer is correct or diagnose misconceptions.
7. When a student submits 'don't know', 'idk', or indicates they are unsure:
   - Call 'evaluate_answer' and 'record_progress' to record the attempt faithfully. Never award unearned mastery merely because an explanation was shown.
   - Provide a supportive, concise explanation grounded in their notes explaining the key concept distinction.
   - Call 'generate_quiz' with that same conceptId to provide one follow-up question so the learner can test their understanding.`;

export interface RunAgentTurnInput {
  provider: LlmProvider;
  userMessage: string;
  action: "start_session" | "submit_answer";
  questionId?: string;
  recoveryForMisconceptionLabel?: string;
  clientAttemptId?: string;
  documentId?: string;
  maxIterations?: number;
  initialMasteryList?: GetMasteryOutput["concepts"];
  signal?: AbortSignal;
}

interface TrustedEvaluationRecord {
  questionId: string;
  answer: string;
  verdict: "correct" | "partially_correct" | "incorrect";
  misconceptionLabel?: string;
  explanation: string;
  evidence?: GenerateQuizOutput["questions"][0]["evidence"];
}

/**
 * Executes a bounded multi-turn LLM agent loop using real MCP tools.
 * Enforces iteration caps, loop detection, argument validation, and evidence verification.
 * Enforces server-side trust boundaries: the model cannot fabricate evaluations or mastery updates.
 */
export async function runAgentTurn(input: RunAgentTurnInput): Promise<AgentTurnResult> {
  const maxIterations = input.maxIterations ?? DEFAULT_MAX_ITERATIONS;
  const toolTraces: ToolTraceEntry[] = [];

  let activeQuestion: GenerateQuizOutput["questions"][0] | undefined;
  let activeEvidence: GenerateQuizOutput["questions"][0]["evidence"] | undefined;
  let activeEvaluation: EvaluateAnswerOutput | undefined;
  let currentMasteryList: GetMasteryOutput["concepts"] = input.initialMasteryList || [];

  // Server-side trust boundary tracking:
  // record_progress can ONLY persist a trusted evaluation generated by evaluate_answer in this turn.
  let trustedEvaluation: TrustedEvaluationRecord | undefined;
  let progressRecorded = false;
  let recordedProgressOutput: RecordProgressOutput | undefined;

  const messages: ChatMessage[] = [
    { role: "system", content: SYSTEM_PROMPT },
  ];

  if (input.action === "submit_answer" && input.questionId) {
    if (isDontKnow(input.userMessage)) {
      messages.push({
        role: "user",
        content: `The student submitted "don't know" for question ID "${input.questionId}". Call evaluate_answer and record_progress to log this attempt without awarding mastery. Give a supportive, concise explanation grounded in their notes explaining the key concept distinction, and call generate_quiz for the same concept to provide one follow-up question.`,
      });
    } else {
      messages.push({
        role: "user",
        content: `The student submitted an answer for question ID "${input.questionId}": "${input.userMessage}". Evaluate this answer using evaluate_answer, record progress with record_progress, and explain the result.`,
      });
    }
  } else {
    messages.push({
      role: "user",
      content: input.userMessage,
    });
  }

  const seenToolCalls = new Set<string>();
  let iteration = 0;
  let finalAssistantMessage = "";

  while (iteration < maxIterations) {
    iteration++;

    let completion;
    try {
      completion = await input.provider.generateCompletion(messages, TUTOR_LLM_TOOLS, input.signal);
    } catch (err: unknown) {
      const errMsg = err instanceof Error ? err.message : String(err);
      throw new Error(`LLM completion failed at iteration ${iteration}: ${errMsg}`);
    }

    if (completion.content) {
      finalAssistantMessage = completion.content;
    }

    // If no tool calls were requested, the model has delivered its final explanation/response
    if (!completion.toolCalls || completion.toolCalls.length === 0) {
      break;
    }

    // Append model's assistant turn with tool_calls
    messages.push({
      role: "assistant",
      content: completion.content || "",
      toolCalls: completion.toolCalls,
    });

    // Execute each requested tool call against the real MCP server
    for (const tc of completion.toolCalls) {
      const callSignature = `${tc.name}:${JSON.stringify(tc.arguments)}`;
      if (seenToolCalls.has(callSignature)) {
        // Prevent infinite loops and duplicate calls
        messages.push({
          role: "tool",
          name: tc.name,
          toolCallId: tc.id,
          content: JSON.stringify({
            error: "duplicate_call",
            message: `Tool ${tc.name} was already executed with identical arguments. Please proceed with existing results.`,
          }),
        });
        continue;
      }
      seenToolCalls.add(callSignature);

      try {
        const result = await executeAgentTool({
          tc,
          toolTraces,
          input,
          trustedEvaluation,
          onEvaluation: (evalRecord) => {
            trustedEvaluation = evalRecord;
          },
          onProgressRecorded: () => {
            progressRecorded = true;
          },
        });

        // Capture structured domain entities from real tool responses
        if (tc.name === "generate_quiz" && (result as GenerateQuizOutput).questions) {
          const qOut = result as GenerateQuizOutput;
          if (qOut.questions.length > 0) {
            activeQuestion = qOut.questions[0];
            activeEvidence = activeQuestion?.evidence;
          }
        } else if (tc.name === "evaluate_answer" && (result as EvaluateAnswerOutput).verdict) {
          activeEvaluation = result as EvaluateAnswerOutput;
          if (activeEvaluation.evidence) {
            activeEvidence = activeEvaluation.evidence;
          }
        } else if (tc.name === "get_mastery" && (result as GetMasteryOutput).concepts) {
          currentMasteryList = (result as GetMasteryOutput).concepts;
        } else if (tc.name === "record_progress") {
          recordedProgressOutput = result as RecordProgressOutput;
          try {
            const masteryRes = await executeMcpTool<Record<string, never>, GetMasteryOutput>(
              "get_mastery",
              {},
            );
            currentMasteryList = masteryRes.result.concepts;
            toolTraces.push(masteryRes.trace);
          } catch {
            // Ignore
          }
        }

        messages.push({
          role: "tool",
          name: tc.name,
          toolCallId: tc.id,
          content: JSON.stringify(result),
        });
      } catch (err: unknown) {
        const errMsg = err instanceof Error ? err.message : String(err);
        messages.push({
          role: "tool",
          name: tc.name,
          toolCallId: tc.id,
          content: JSON.stringify({ error: "tool_execution_failed", message: errMsg }),
        });
      }
    }
  }

  // Trust boundary safeguard:
  // If this was an answer submission and evaluate_answer succeeded, ensure progress is persisted
  // even if the model stopped or failed to invoke record_progress.
  if (input.action === "submit_answer" && trustedEvaluation && !progressRecorded) {
    try {
      const res = await executeMcpTool<
        {
          questionId: string;
          answer: string;
          verdict: "correct" | "partially_correct" | "incorrect";
          misconceptionLabel?: string;
          recoveryForMisconceptionLabel?: string;
          clientAttemptId?: string;
        },
        RecordProgressOutput
      >("record_progress", {
        questionId: trustedEvaluation.questionId,
        answer: trustedEvaluation.answer,
        verdict: trustedEvaluation.verdict,
        misconceptionLabel: trustedEvaluation.misconceptionLabel,
        recoveryForMisconceptionLabel: input.recoveryForMisconceptionLabel,
        clientAttemptId: input.clientAttemptId,
      });
      recordedProgressOutput = res.result;
      toolTraces.push(res.trace);
      progressRecorded = true;

      // Refresh mastery state
      const masteryRes = await executeMcpTool<{ documentId?: string }, GetMasteryOutput>(
        "get_mastery",
        { documentId: input.documentId },
      );
      currentMasteryList = masteryRes.result.concepts;
      toolTraces.push(masteryRes.trace);
    } catch {
      // Non-fatal if post-turn persistence fails
    }
  }

  // Ensure fresh mastery list is loaded if none was queried
  if (currentMasteryList.length === 0) {
    try {
      const masteryRes = await executeMcpTool<Record<string, never>, GetMasteryOutput>(
        "get_mastery",
        {},
      );
      currentMasteryList = masteryRes.result.concepts;
      toolTraces.push(masteryRes.trace);
    } catch {
      // Ignore
    }
  }

  // Follow-up question guardrail for misconception recovery & "don't know":
  // If the student diagnosed a misconception and no follow-up quiz was called by the agent,
  // ensure a targeted recovery question is attached.
  if (
    input.action === "submit_answer" &&
    !activeQuestion &&
    activeEvaluation?.conceptId
  ) {
    if (activeEvaluation.verdict === "incorrect" && activeEvaluation.misconceptionLabel) {
      try {
        const quizRes = await executeMcpTool<
          {
            conceptId: string;
            count: number;
            focus: "new" | "weak" | "review";
            misconceptionLabel?: string;
            excludeQuestionId?: string;
          },
          GenerateQuizOutput
        >("generate_quiz", {
          conceptId: activeEvaluation.conceptId,
          count: 1,
          focus: "weak",
          misconceptionLabel: activeEvaluation.misconceptionLabel,
          excludeQuestionId: input.questionId,
        });
        toolTraces.push(quizRes.trace);
        if (quizRes.result.questions.length > 0) {
          activeQuestion = quizRes.result.questions[0];
          activeEvidence = activeQuestion?.evidence;
        }
      } catch {
        // Non-fatal
      }
    } else if (isDontKnow(input.userMessage)) {
      try {
        const quizRes = await executeMcpTool<
          {
            conceptId: string;
            count: number;
            focus: "new" | "weak" | "review";
            excludeQuestionId?: string;
          },
          GenerateQuizOutput
        >("generate_quiz", {
          conceptId: activeEvaluation.conceptId,
          count: 1,
          focus: "new",
          excludeQuestionId: input.questionId,
        });
        toolTraces.push(quizRes.trace);
        if (quizRes.result.questions.length > 0) {
          activeQuestion = quizRes.result.questions[0];
          activeEvidence = activeQuestion?.evidence;
        }
      } catch {
        // Non-fatal
      }
    }
  }

  // Grounding and Verification Guardrail:
  // If activeQuestion exists, verify its evidence status is 'verified'.
  // If not, clear the ungrounded question.
  if (activeQuestion && activeQuestion.evidence?.status !== "verified") {
    activeQuestion = undefined;
    activeEvidence = undefined;
  }

  if (!finalAssistantMessage) {
    finalAssistantMessage = activeQuestion
      ? `Here is a question from your study notes on ${activeQuestion.conceptId}:`
      : "I have reviewed your request against your study notes.";
  }

  return {
    message: finalAssistantMessage,
    question: activeQuestion,
    evidence: activeEvidence,
    evaluation: activeEvaluation
      ? {
          verdict: activeEvaluation.verdict,
          explanation: activeEvaluation.explanation,
          misconceptionLabel: activeEvaluation.misconceptionLabel,
          recoveryCitation: activeEvaluation.recoveryCitation,
          misconceptionResolved: recordedProgressOutput?.misconceptionResolved,
          resolvedMisconceptionLabel: recordedProgressOutput?.resolvedMisconceptionLabel,
          recoveryStatus: recordedProgressOutput?.recoveryStatus,
        }
      : undefined,
    masteryList: currentMasteryList,
    toolTraces,
    providerUsed: "llm",
  };
}

interface ExecuteAgentToolContext {
  tc: ToolCall;
  toolTraces: ToolTraceEntry[];
  input: RunAgentTurnInput;
  trustedEvaluation?: TrustedEvaluationRecord;
  onEvaluation: (evalRecord: TrustedEvaluationRecord) => void;
  onProgressRecorded: () => void;
}

/**
 * Dispatches individual tool calls to real MCP tools with strict argument validation
 * and cryptographic/server-side trust boundary guarantees.
 */
async function executeAgentTool(ctx: ExecuteAgentToolContext): Promise<unknown> {
  const { tc, toolTraces, input, trustedEvaluation, onEvaluation, onProgressRecorded } = ctx;
  const args = tc.arguments || {};

  switch (tc.name) {
    case "search_study_notes": {
      const query = typeof args.query === "string" ? args.query : "database";
      const limit = typeof args.limit === "number" ? args.limit : 3;
      const res = await executeMcpTool<{ query: string; limit: number }, SearchStudyNotesOutput>(
        "search_study_notes",
        { query, limit },
      );
      toolTraces.push(res.trace);
      return res.result;
    }

    case "get_mastery": {
      const conceptIds = Array.isArray(args.conceptIds)
        ? (args.conceptIds as string[])
        : undefined;
      const res = await executeMcpTool<{ conceptIds?: string[] }, GetMasteryOutput>(
        "get_mastery",
        conceptIds ? { conceptIds } : {},
      );
      toolTraces.push(res.trace);
      return res.result;
    }

    case "generate_quiz": {
      const conceptId = typeof args.conceptId === "string" ? args.conceptId : "1nf";
      const focus =
        args.focus === "weak" || args.focus === "review" ? args.focus : "new";
      const count = typeof args.count === "number" ? args.count : 1;
      const res = await executeMcpTool<
        { conceptId: string; focus: "new" | "weak" | "review"; count: number },
        GenerateQuizOutput
      >("generate_quiz", { conceptId, focus, count });
      toolTraces.push(res.trace);
      return res.result;
    }

    case "evaluate_answer": {
      // Trust boundary: Bind question and answer to the actual student submission if in submit_answer
      const questionId =
        input.action === "submit_answer" && input.questionId
          ? input.questionId
          : String(args.questionId || "");
      const answer =
        input.action === "submit_answer"
          ? input.userMessage
          : String(args.answer || "");

      const res = await executeMcpTool<
        { questionId: string; answer: string },
        EvaluateAnswerOutput
      >("evaluate_answer", { questionId, answer });
      toolTraces.push(res.trace);

      // Record trusted server evaluation
      onEvaluation({
        questionId,
        answer,
        verdict: res.result.verdict,
        misconceptionLabel: res.result.misconceptionLabel,
        explanation: res.result.explanation,
        evidence: res.result.evidence,
      });

      return res.result;
    }

    case "record_progress": {
      // Trust boundary: The model CANNOT fabricate answer evaluations or arbitrary mastery updates.
      // record_progress can ONLY persist a trusted server-side evaluation belonging to the actual
      // question and student submission being handled.
      if (!trustedEvaluation) {
        throw new Error(
          "Trust boundary violation: record_progress requires a prior trusted evaluation from evaluate_answer in this turn.",
        );
      }

      // Enforce parameters from trustedEvaluation (ignore any model-fabricated verdict or answers)
      const questionId = trustedEvaluation.questionId;
      const answer = trustedEvaluation.answer;
      const verdict = trustedEvaluation.verdict;
      const misconceptionLabel = trustedEvaluation.misconceptionLabel;

      const res = await executeMcpTool<
        {
          questionId: string;
          answer: string;
          verdict: "correct" | "partially_correct" | "incorrect";
          misconceptionLabel?: string;
          clientAttemptId?: string;
        },
        RecordProgressOutput
      >("record_progress", {
        questionId,
        answer,
        verdict,
        misconceptionLabel,
        clientAttemptId: input.clientAttemptId,
      });
      toolTraces.push(res.trace);
      onProgressRecorded();
      return res.result;
    }

    default:
      throw new Error(`Unknown MCP tool requested: ${tc.name}`);
  }
}
